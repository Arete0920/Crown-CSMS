import { expect, test, type Page, type Response } from "@playwright/test";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// An intentionally destructive, fictional-only browser rehearsal. It is NOT
// the public/hosted SGO intake, a unit test with route mocks, or a repeatable
// read-only audit. Re-create isolated Heritage SQLite before rerunning.
const FRONTEND = "http://127.0.0.1:4173";
const BACKEND = "http://127.0.0.1:8000";
const API = "/api/v1/jireh-sgo";
const enabled = process.env.CROWN_SGO_LOCAL_E2E === "1";
const required = process.env.CROWN_REQUIRE_SGO_BROWSER_PROOF === "1";
const credentialFile = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../../../.local-backups/heritage-demo/sgo-credentials.txt",
);
if (required && !enabled) {
  throw new Error("Required fictional SGO browser proof cannot be skipped.");
}
if (required && process.env.CROWN_SGO_LOCAL_CREDENTIALS !== credentialFile) {
  throw new Error("Use only the isolated Heritage local SGO credential path.");
}

type Role = "family" | "processor" | "partner";
type Partner = "de" | "pa";
type Program = {
  id: string; organization: string; consent_version: string;
  application_id: string | null;
};
type Case = {
  id: string; program_id: string; status: string;
  revision: number; grade_level: string; funds_status: string;
  consented_at: string;
};

function api(response: Response, method: string, path: string | RegExp): boolean {
  const url = new URL(response.url());
  return (url.origin === new URL(FRONTEND).origin || url.origin === new URL(BACKEND).origin)
    && response.request().method() === method
    && (typeof path === "string" ? url.pathname === path : path.test(url.pathname));
}

function account(partner: Partner, role: Role) {
  const text = readFileSync(credentialFile, "utf8");
  if (!text.startsWith("# CROWN fictional SGO local demo accounts.")) {
    throw new Error("Refusing credentials not generated by the fictional SGO seeder.");
  }
  const org = partner === "de" ? "Fictional Delaware SGO (demo)" : "Fictional Pennsylvania SGO (demo)";
  const start = text.indexOf("[" + org + "]");
  if (start < 0) throw new Error("Missing fictional partner credential section.");
  const next = text.indexOf("\n[", start + 1);
  const block = text.slice(start, next < 0 ? undefined : next);
  const label = role === "family" ? "Family login" : role === "processor"
    ? "Processor login" : "Partner SGO admin (no automatic processor rights)";
  const line = block.split(/\r?\n/).find((item) => item.startsWith(label + ": "));
  const pair = line?.slice(label.length + 2).split(" / ");
  if (pair?.length !== 2 || pair[0] !== `sgo_demo_${partner}_${role}` || !pair[1]) {
    throw new Error("Fictional SGO account identity or credential format mismatch.");
  }
  return { username: pair[0], password: pair[1] };
}

async function login(page: Page, partner: Partner, role: Role) {
  await page.goto(FRONTEND + "/jireh-sgo/sign-in", { waitUntil: "domcontentloaded" });
  await expect(page.getByLabel("Synthetic account username")).toBeVisible();
  const tokenResponse = page.waitForResponse((response) =>
    api(response, "POST", "/api/v1/auth/token/"),
  );
  const credentials = account(partner, role);
  await page.getByLabel("Synthetic account username").fill(credentials.username);
  await page.getByLabel("Synthetic account password").fill(credentials.password);
  await page.getByRole("button", { name: "Sign in to fictional SGO" }).click();
  const signed = await tokenResponse;
  expect(signed.status(), "Real Django JWT login must succeed").toBe(200);
  await expect(page).toHaveURL(/\/jireh-sgo\/intake$/, { timeout: 30_000 });
  await expect.poll(async () => page.evaluate(
    () => !!sessionStorage.getItem("crown.jwt.access"),
  )).toBe(true);
}

async function switchAccount(page: Page) {
  await page.getByRole("button", { name: "Switch fictional SGO account" }).click();
  await expect(page).toHaveURL(/\/jireh-sgo\/sign-in$/);
  await expect.poll(async () => page.evaluate(
    () => !!sessionStorage.getItem("crown.jwt.access"),
  )).toBe(false);
}

test.describe.serial("SGO partner-processor fictional browser acceptance", () => {
  test.skip(!enabled, "Only opt in on a fresh, isolated Heritage local SQLite instance.");

  test("real browser: consent -> POST/GET -> processor correction -> family resubmission -> partner denials", async ({ page, request }) => {
    test.setTimeout(240_000);
    const catalog = await request.get(BACKEND + "/api/v1/sandbox/catalog/");
    expect(catalog.status()).toBe(200);
    const inventory = await catalog.json();
    expect(inventory.schools?.map((school: { key: string }) => school.key)).toEqual(["heritage-core"]);

    // A fresh applicant grant is necessary. Existing family submissions must
    // not be silently treated as this run's evidence, or auto-deleted.
    const programRequest = page.waitForResponse((response) =>
      api(response, "GET", API + "/family/programs/"),
    );
    await login(page, "de", "family");
    const initial = await programRequest;
    expect(initial.status()).toBe(200);
    const programs = await initial.json();
    expect(programs.synthetic_only).toBe(true);
    expect(programs.funds_status).toBe("NONCASH_ONLY");
    expect(programs.programs).toHaveLength(1);
    const program = programs.programs[0] as Program;
    expect(program.organization).toContain("Delaware");
    expect(program.application_id, "Rebuild isolated demo before repeat browser proof").toBeNull();
    await expect(page.getByLabel("Partner SGO and program")).toHaveValue(program.id);
    await expect(page.getByRole("button", { name: "Submit fictional application" })).toBeDisabled();
    await expect(page.locator('input[type="file"]')).toHaveCount(0);
    await page.getByLabel("Fictional grade level").selectOption("K");
    await page.getByRole("checkbox", { name: /I consent to submitting this fictional application/i }).check();

    const submission = page.waitForResponse((response) =>
      api(response, "POST", API + "/family/submit/"),
    );
    const firstReadback = page.waitForResponse((response) =>
      api(response, "GET", /^\/api\/v1\/jireh-sgo\/family\/applications\/[a-f0-9-]{36}\/$/i),
    );
    await page.getByRole("button", { name: "Submit fictional application" }).click();
    const posted = await submission;
    expect(posted.status()).toBe(201);
    const postedHeaders = await posted.request().allHeaders();
    expect(postedHeaders.authorization).toMatch(/^Bearer\s+\S+/);
    expect(postedHeaders["x-school-id"]).toBeUndefined();
    const created = (await posted.json()).application as Case;
    expect(created.id).toMatch(/^[a-f0-9-]{36}$/i);
    expect(created.program_id).toBe(program.id);
    expect([created.status, created.revision, created.funds_status]).toEqual(["SUBMITTED", 1, "NONCASH_ONLY"]);
    expect(created.consented_at).toBeTruthy();

    const saved = await firstReadback;
    expect(saved.status()).toBe(200);
    expect(new URL(saved.url()).pathname).toBe(API + "/family/applications/" + created.id + "/");
    expect(saved.headers()["cache-control"]).toContain("no-store");
    expect((await saved.json()).application.id).toBe(created.id);
    await expect(page.getByText(/Saved\. The submitted fictional application was read back/)).toBeVisible();
    await expect(page.getByText("Persistent application readback")).toBeVisible();

    const reloaded = page.waitForResponse((response) =>
      api(response, "GET", API + "/family/applications/" + created.id + "/"),
    );
    await page.reload({ waitUntil: "domcontentloaded" });
    expect((await reloaded).status()).toBe(200);
    await expect(page.getByText("SUBMITTED", { exact: true })).toBeVisible();

    // Independent delegated processor identity, never inferred from SGO ADMIN.
    await switchAccount(page);
    const queueResponse = page.waitForResponse((response) =>
      api(response, "GET", /^\/api\/v1\/jireh-sgo\/processor\/programs\/[a-f0-9-]{36}\/queue\/$/i),
    );
    await login(page, "de", "processor");
    const queue = await queueResponse;
    expect(queue.status()).toBe(200);
    const queueBody = await queue.json();
    expect(queueBody.authority).toBe("PROCESSOR_VERIFICATION_ONLY");
    expect(queueBody.program_id).toBe(program.id);
    expect(queueBody.applications.map((item: Case) => item.id)).toContain(created.id);
    const row = page.getByRole("row").filter({ hasText: created.id.slice(0, 8) });
    await expect(row).toBeVisible();

    const correctionPost = page.waitForResponse((response) =>
      api(response, "POST", API + "/processor/applications/" + created.id + "/request-correction/"),
    );
    const correctedQueue = page.waitForResponse((response) =>
      api(response, "GET", API + "/processor/programs/" + program.id + "/queue/"),
    );
    await row.getByRole("button", { name: "Request correction" }).click();
    const correctionResponse = await correctionPost;
    expect(correctionResponse.status()).toBe(200);
    const correction = (await correctionResponse.json()).application as Case;
    expect([correction.status, correction.revision]).toEqual(["CORRECTION_REQUESTED", 2]);
    expect((await correctedQueue).status()).toBe(200);
    await expect(page.getByText(/Nonbinding verification correction request recorded and read back/)).toBeVisible();

    await switchAccount(page);
    const requested = page.waitForResponse((response) =>
      api(response, "GET", API + "/family/applications/" + created.id + "/"),
    );
    await login(page, "de", "family");
    expect((await requested).status()).toBe(200);
    await expect(page.getByText("CORRECTION_REQUESTED", { exact: true })).toBeVisible();
    await page.getByLabel("Correct or confirm fictional grade").selectOption("2");

    const amendPost = page.waitForResponse((response) =>
      api(response, "POST", API + "/family/applications/" + created.id + "/correct/"),
    );
    const amendRead = page.waitForResponse((response) =>
      api(response, "GET", API + "/family/applications/" + created.id + "/"),
    );
    await page.getByRole("button", { name: "Save correction and resubmit" }).click();
    const amended = await amendPost;
    expect(amended.status()).toBe(200);
    const amendedCase = (await amended.json()).application as Case;
    expect([amendedCase.status, amendedCase.revision, amendedCase.grade_level]).toEqual(["RESUBMITTED", 3, "2"]);
    const verified = await amendRead;
    expect(verified.status()).toBe(200);
    const reread = (await verified.json()).application as Case;
    expect([reread.id, reread.revision, reread.status, reread.grade_level]).toEqual([created.id, 3, "RESUBMITTED", "2"]);
    await expect(page.getByText(/Correction saved, read back and resubmitted/)).toBeVisible();
    const finalGet = page.waitForResponse((response) =>
      api(response, "GET", API + "/family/applications/" + created.id + "/"),
    );
    await page.reload({ waitUntil: "domcontentloaded" });
    expect((await finalGet).status()).toBe(200);
    await expect(page.getByText("RESUBMITTED", { exact: true })).toBeVisible();

    // Another fictional SGO family cannot read Delaware case with its own
    // genuinely issued token. Do not use mocked fetches, stolen tokens or roles.
    await switchAccount(page);
    const paPrograms = page.waitForResponse((response) =>
      api(response, "GET", API + "/family/programs/"),
    );
    await login(page, "pa", "family");
    const paList = await paPrograms;
    const paBody = await paList.json();
    expect(paBody.programs).toHaveLength(1);
    expect(paBody.programs[0].organization).toContain("Pennsylvania");
    expect(paBody.programs[0].id).not.toBe(program.id);
    const paBearer = (await paList.request().allHeaders()).authorization;
    expect(paBearer).toMatch(/^Bearer\s+\S+/);
    const denied = await request.get(BACKEND + API + "/family/applications/" + created.id + "/", {
      headers: { Authorization: paBearer },
    });
    expect(denied.status()).toBe(403);
    await expect(page.getByText("Persistent application readback")).toHaveCount(0);

    // Administrative partner membership alone is not an applicant grant or
    // a processor assignment. It cannot acquire either journey through login.
    await switchAccount(page);
    const partnerFamily = page.waitForResponse((response) =>
      api(response, "GET", API + "/family/programs/"),
    );
    const partnerProcessor = page.waitForResponse((response) =>
      api(response, "GET", API + "/processor/programs/"),
    );
    await login(page, "de", "partner");
    expect((await (await partnerFamily).json()).programs).toEqual([]);
    expect((await (await partnerProcessor).json()).programs).toEqual([]);
    await expect(page.getByText(/No fictional family grants/)).toBeVisible();
    await expect(page.getByText(/No delegated processor assignment/)).toBeVisible();
    await expect(page.getByRole("button", { name: "Submit fictional application" })).toHaveCount(0);
    await expect(page.getByRole("button", { name: "Request correction" })).toHaveCount(0);
  });
});
